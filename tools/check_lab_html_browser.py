#!/usr/bin/env python3
"""Exercise offline exported HTML in a fresh headless Chrome profile.

python3 tools/check_lab_html_browser.py REAL.zip FIXTURE.zip
FIXTURE.zip is generated by HtmlReportCheck on Android. No server or downloads.
"""
import argparse
from pathlib import Path
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
JS = r'''
(async function(){
const assert=(condition,message)=>{if(!condition)throw Error(message);};
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const until=async(predicate,message)=>{for(let i=0;i<30&&!predicate();++i)await wait(100);assert(predicate(),message);};
try {
 const $=id=>document.getElementById(id),read=id=>JSON.parse($(id).textContent);
 const cases=read('cases-data'),segments=read('segments-data');
 assert(cases.length===EXPECTED,'all expected summaries');
 assert($('case-rows').children.length===Math.min(50,cases.length),'bounded table DOM');
 assert($('totals').textContent.includes('Finished')||$('totals').textContent.includes('finished'),'summary rendered');
 assert(!window.PWNED&&!document.querySelector('img[src=x]'),'literal strings stay text');
 assert($('resource-plots').querySelectorAll('svg').length===4,'four resource graphs');
 for(const p of document.querySelectorAll('svg path'))assert(!/NaN|Infinity/.test(p.getAttribute('d')),'valid graph coordinates');
 const current=segments[Number($('segment').value)],profile=read(current.id);
 const peak=profile.samples.reduce((a,b)=>(b[1]||0)>(a[1]||0)?b:a);
 const svg=$('resource-plots').querySelector('svg'),bounds=svg.getBoundingClientRect(),rows=profile.samples;
 const width=svg.viewBox.baseVal.width,pos=53+(peak[0]-rows[0][0])/(rows[rows.length-1][0]-rows[0][0])*(width-16-53);
 svg.dispatchEvent(new PointerEvent('pointermove',{clientX:bounds.left+bounds.width*pos/width,clientY:bounds.top+50}));
 assert($('resource-plots').querySelector('figcaption').textContent.includes('test_pool'),'peak identifies active suite');
 $('search').value='test_pool';$('search').dispatchEvent(new Event('input'));await wait(200);
 assert($('case-rows').textContent.includes('test_pool'),'filter renders');
 assert(!$('case-rows').textContent.includes('test_waveform'),'filter excludes other suites');
 $('search').value='';$('search').dispatchEvent(new Event('input'));await wait(200);
 if(FIXTURE){
  assert(segments.length===2,'all resource segments present');
  $('segment').value='0';$('segment').dispatchEvent(new Event('change'));
  assert($('resource-note').textContent.includes('resources-segment-1.json'),'segment switching');
  $('next').click();assert($('page').textContent==='51–100','second page');
  $('next').click();assert($('page').textContent==='101–125','third page');
  const buttons=$('case-rows').querySelectorAll('button');buttons[buttons.length-1].click();
  assert($('goodput-plots').querySelectorAll('svg').length===2,'delivered and ACK graphs');
  assert($('case-detail').textContent.includes('<'+'/script>'),'literal log text rendered');
  assert(!window.PWNED&&!document.querySelector('img[src=x]'),'case rendering stays text');
  const record=read('previews-data').slice(-1)[0];
  $('case-rows').querySelector('button').click();
  assert($('goodput-plots').querySelectorAll('svg').length===0,'reset detail before file loading');
  const transfer=new DataTransfer();transfer.items.add(new File([JSON.stringify(record.result)],record.file,{type:'application/json'}));
  $('case-file').files=transfer.files;$('case-file').dispatchEvent(new Event('change'));await until(()=>$('goodput-plots').querySelectorAll('svg').length===2,'local file finishes reading');
  assert($('goodput-plots').querySelectorAll('svg').length===2,'local JSON case loading');
  assert(!$('report-error').textContent,'file load succeeds');
  const wrong={...record.result,revision:'different-payload'};
  const bad=new DataTransfer();bad.items.add(new File([JSON.stringify(wrong)],record.file,{type:'application/json'}));
  $('case-file').files=bad.files;$('case-file').dispatchEvent(new Event('change'));await until(()=>$('report-error').textContent.includes('different native payload'),'rejected file finishes reading');
  assert($('report-error').textContent.includes('different native payload'),'different payload rejected');
  $('report-error').textContent='';
 }
 assert(MOBILE?document.body.scrollWidth<=390:document.documentElement.scrollWidth<=window.innerWidth,'page fits viewport');window.scrollTo(0,0);document.body.dataset.qa='passed';
 const result=document.createElement('p');result.id='qa-result';result.textContent='PASS offline browser: summary, graphs, CPU case marker, filters, pagination, file loading, goodput and safe literal text';document.body.append(result);
} catch(error){document.body.dataset.qa='failed';const p=document.createElement('pre');p.id='qa-error';p.textContent=error.stack||String(error);document.body.append(p);}
})();
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('real', type=Path)
    ap.add_argument('fixture', type=Path)
    ap.add_argument('--mobile', action='store_true')
    ap.add_argument('--chrome', type=Path, default=Path('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'))
    ap.add_argument('--output', type=Path, default=ROOT / 'native/build-lab/html-browser')
    args = ap.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    for name, archive, count, fixture in [('real', args.real, 26, False), ('fixture', args.fixture, 125, True)]:
        with zipfile.ZipFile(archive) as z:
            html = z.read('report.html').decode()
        test = JS.replace('EXPECTED', str(count)).replace('FIXTURE', str(fixture).lower()).replace('MOBILE', str(args.mobile).lower())
        if args.mobile:
            # Desktop Chrome enforces a 500px minimum inner viewport on macOS.
            # Constrain the report itself to 390px to test its actual layout,
            # rather than producing a misleading clipped 500px rendering.
            html = html.replace('</head>', '<style>body{width:390px;max-width:100%}</style></head>')
        source = args.output / f'{name}-check.html'
        source.write_text(html.replace('</body>', '<script>' + test + '</script></body>'))
        with tempfile.TemporaryDirectory(prefix='data2g-html-chrome-', dir='/private/tmp') as profile:
            result = subprocess.run([str(args.chrome), '--headless=new', '--disable-gpu', '--no-first-run',
                                     '--disable-background-networking', '--disable-default-apps', '--no-default-browser-check',
                                     f'--user-data-dir={profile}', ('--window-size=500,1800' if args.mobile else '--window-size=1440,1800'), '--virtual-time-budget=8000',
                                     f'--screenshot={args.output / (name + ".png")}', '--dump-dom', source.resolve().as_uri()],
                                    capture_output=True, text=True, timeout=60)
        (args.output / f'{name}-dom.html').write_text(result.stdout)
        (args.output / f'{name}-chrome.log').write_text(result.stderr)
        if result.returncode or 'data-qa="passed"' not in result.stdout:
            raise RuntimeError(f'{name} browser check failed; inspect {args.output}/{name}-dom.html and Chrome log')
        print(f'{name}: offline browser checks passed; screenshot {args.output / (name + ".png")}')


if __name__ == '__main__':
    main()
